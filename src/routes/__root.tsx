function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        {/* Optional runtime settings for the phone app (which website to talk to). Must load before the app. */}
        <script src="/config.js" />
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  // Signing in or out anywhere in the app refreshes what every page shows.
  useEffect(() => { const off = onAuthChange((event) => {
    router.invalidate();
    if (event === "SIGNED_OUT") queryClient.clear();
    else void queryClient.invalidateQueries();
  }); return () => { off(); }; }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-center" />
    </QueryClientProvider>
  );
}
